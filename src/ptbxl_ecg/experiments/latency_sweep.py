"""C2: sweep width/depth per architecture, measure CPU latency of each variant,
and write a training config for the largest variant that fits the budget.

    python -m ptbxl_ecg.experiments.latency_sweep configs/c2_sweep.yaml
    # then train: python -m ptbxl_ecg.train configs/generated/c2_<arch>.yaml --seeds 0 1 2

Latency does not depend on trained weights, so variants are timed untrained.
Run on the deployment-class CPU.
"""
from __future__ import annotations

import argparse
import itertools
from pathlib import Path

import pandas as pd
import yaml

from ptbxl_ecg.engine import classifier_wrapper
from ptbxl_ecg.experiments.common import TABLE_DIR, ensure_dirs
from ptbxl_ecg.latency import benchmark_module, hardware
from ptbxl_ecg.models import build_model, count_params
from ptbxl_ecg.utils.config import load_config, set_by_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("config")
    args = parser.parse_args()
    sweep = yaml.safe_load(Path(args.config).read_text())
    cfg_dir = Path(args.config).parent
    ensure_dirs()

    rows = []
    for arch, spec in sweep["archs"].items():
        keys = list(spec["grid"])
        for combo in itertools.product(*(spec["grid"][k] for k in keys)):
            overrides = dict(zip(keys, combo))
            cfg = load_config(cfg_dir / spec["base_config"])
            for k, v in overrides.items():
                set_by_path(cfg, k, v)
            model = build_model(cfg["model"])
            module = classifier_wrapper(model, cfg, total_len=10 * cfg["data"]["sampling_rate"])
            stats = benchmark_module(module, sweep["threads"], sweep["n_warmup"], sweep["n_runs"], total_len=10 * cfg["data"]["sampling_rate"])
            row = {"arch": arch, **{k: str(v) for k, v in overrides.items()}, "n_params": count_params(model), **stats}
            rows.append(row)
            print(row, flush=True)

    df = pd.DataFrame(rows)
    df["hardware"] = hardware()
    df["threads"] = sweep["threads"]
    df["fits_budget"] = df[sweep["budget_stat"]] <= sweep["budget_ms"]
    df.to_csv(TABLE_DIR / "c2_latency_sweep.csv", index=False)

    out_dir = cfg_dir / "generated"
    out_dir.mkdir(exist_ok=True)
    for arch, spec in sweep["archs"].items():
        ok = df[(df["arch"] == arch) & df["fits_budget"]]
        if ok.empty:
            print(f"!! no {arch} variant fits {sweep['budget_ms']} ms ({sweep['budget_stat']})")
            continue
        best = ok.sort_values(sweep["select_by"], ascending=False).iloc[0]
        model_over: dict = {}
        for k in spec["grid"]:
            set_by_path(model_over, k, yaml.safe_load(best[k]))
        generated = {
            "inherit": f"../{spec['base_config']}",
            "name": f"c2_{arch}",
            "experiment": "C2",
            **model_over,
            "c2_selection": {
                "budget_ms": sweep["budget_ms"], "stat": sweep["budget_stat"], "measured_ms": float(best[sweep["budget_stat"]]),
                "n_params": int(best["n_params"]), "hardware": hardware(),
            },
        }
        path = out_dir / f"c2_{arch}.yaml"
        path.write_text("# Generated by src/experiments/latency_sweep.py, do not edit by hand.\n" + yaml.safe_dump(generated, sort_keys=False))
        print(f"selected {arch}: {model_over} ({best[sweep['budget_stat']]:.2f} ms) -> {path}")


if __name__ == "__main__":
    main()
